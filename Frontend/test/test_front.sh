# Vite를 사용하여 React + TypeScript 프로젝트 생성
npm create vite@latest my-test-app --template react-ts

# 프로젝트 디렉토리로 이동
cd my-test-app

# React, Redux, TailwindCSS 설치
npm install react@18.2.0 react-dom@18.2.0 react-redux redux @reduxjs/toolkit redux-thunk tailwindcss postcss autoprefixer

# TailwindCSS 초기화
npx tailwindcss init -p